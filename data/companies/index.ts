export function getCompanyById(id: string): CompanyData | undefined {
  return COMPANIES.find((c) => c.id === id);
}

export function getCompaniesByCategory(category: CompanyCategory): CompanyData[] {
  return COMPANIES.filter((c) => c.category === category);
}

export function buildCompanyContextPrompt(companyId: string): string {
  const company = getCompanyById(companyId);
  if (!company) return "";

  return `
Target Company: ${company.name}
Interview Style: ${company.interviewStyle}
Difficulty Tier: ${company.difficultyTier}
Typical Rounds: ${company.typicalRounds.join(" → ")}
Focus Areas: ${company.focusAreas.join(", ")}
E&TC Topics Emphasized: ${company.etcTopics.join(", ")}
Question Style: ${company.questionStyle}
Known For: ${company.knownFor}

Generate questions that match ${company.name}'s actual interview pattern and depth level.
`;
}

